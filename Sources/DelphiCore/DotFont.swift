import Foundation

/// A bitmap font for a dot-matrix board. Each glyph is a run of columns; bit 0 of a column is the top row.
public nonisolated struct DotFont: Sendable {
    public let name: String
    public let height: Int
    private let glyphs: [Character: [UInt16]]

    /// `art` maps each character to its rows, `#` lit and `.` dark; a glyph's width is its row length.
    init(name: String, height: Int, art: [Character: [String]]) {
        self.name = name
        self.height = height
        var glyphs: [Character: [UInt16]] = [:]
        for (character, rows) in art {
            let width = rows.first?.count ?? 0
            glyphs[character] = (0..<width).map { x in
                rows.enumerated().reduce(UInt16(0)) { mask, row in
                    Array(row.element)[x] == "#" ? mask | 1 << row.offset : mask
                }
            }
        }
        self.glyphs = glyphs
    }

    public func covers(_ character: Character) -> Bool { glyphs[character] != nil }

    /// Columns for `text`, one dark column between glyphs; a character the font lacks draws as `?`.
    public func columns(_ text: String, spacing: Int = 1) -> [UInt16] {
        var out: [UInt16] = []
        for character in text {
            guard let glyph = glyphs[character] ?? glyphs["?"] else { continue }
            if !out.isEmpty { out += Array(repeating: 0, count: spacing) }
            out += glyph
        }
        return out
    }

    public static let all = [station]

    public static let station = DotFont(name: "Station", height: 7, art: stationArt)

    #if DEBUG
    public static func selfCheck() {
        for (character, rows) in stationArt {
            assert(rows.count == 7, "\(character) has \(rows.count) rows")
            assert(Set(rows.map(\.count)).count == 1, "\(character) rows differ in width")
        }
        let required = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,:;!?-+/()'\"%°‹›·=_"
        for character in required { assert(station.covers(character), "station lacks \(character)") }
        assert(station.columns("I") == [0b1000001, 0b1111111, 0b1000001])
        assert(station.columns("ii").count == 3)
        // fallback is ?
        assert(station.columns("\u{2603}") == station.columns("?"))
    }
    #endif
}

